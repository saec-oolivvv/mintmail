#!/usr/bin/env python3
"""Génère docs/AIDE.md (français) et docs/HELP.md (anglais) à partir de l'aide intégrée : une seule source de vérité."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from mintmail import help_content as H, i18n   # noqa: E402

version = open(os.path.join(ROOT, "VERSION"), encoding="utf-8").read().strip()
ctx = {"version": version, "config": "~/.config/mintmail", "data": "~/.local/share/mintmail", "log": "~/.local/share/mintmail/mintmail.log"}
for lang, fname, title, note, mono in (
        ("fr", "AIDE.md", "Aide de MintMail %s", "_Généré par `make docs` depuis l'aide intégrée (touche F1 dans l'application)._",
         ("Tous les raccourcis clavier", "Options de la commande mintmail")),
        ("en", "HELP.md", "MintMail %s help", "_Generated by `make docs` from the built-in help (F1 key in the application)._",
         ("All keyboard shortcuts", "Options of the mintmail command"))):
    i18n.set_language(lang)
    out = ["# %s\n" % (title % version), note + "\n"]
    for s in H.sections(ctx):
        out.append("\n## %s\n" % s["title"])
        for t, body in s["items"]:
            out.append("\n### %s\n\n%s\n" % (t, ("```\n%s\n```" % body) if t in mono else body.replace("\n", "  \n")))
    with open(os.path.join(ROOT, "docs", fname), "w", encoding="utf-8") as f:
        f.write("".join(out))
    print("docs/%s écrit" % fname)
i18n.set_language("fr")
