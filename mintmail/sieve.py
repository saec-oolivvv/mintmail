"""Sieve (RFC 5228) sans Qt : génère le script d'absence + règles MintMail pour qu'ils tournent AUSSI SUR LE SERVEUR (MintMail fermé),
client ManageSieve minimal (RFC 5804) et import des filtres Thunderbird (msgFilterRules.dat). Gmail et Microsoft 365 n'offrent pas Sieve."""
import base64
import re
import socket
import ssl
import urllib.parse

SCRIPT_NAME = "mintmail"
ACTIONS = {"archive": ('fileinto', "Archive"), "trash": ('fileinto', "Trash"), "spam": ('fileinto', "Junk"),
           "read": ('addflag', "\\Seen"), "star": ('addflag', "\\Flagged")}      # « pin » n'a pas d'équivalent Sieve : ignoré
FIELDS = {"from": ['"from"'], "subject": ['"subject"'], "to": ['"to"', '"cc"']}


VACATION = 'if allof (currentdate :value "ge" "date" %s, currentdate :value "le" "date" %s) {\n  vacation :days 1%s :subject %s %s;\n}'      # i18n: skip


def q(s) -> str:
    """Chaîne Sieve entre guillemets."""
    return '"%s"' % str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\r", "")


def rule_test(rule):
    hdr = FIELDS.get(rule.get("field"))
    txt = (rule.get("text") or "").strip()
    if not hdr or not txt:
        return None
    return 'header :contains [%s] %s' % (", ".join(hdr), q(txt))


def rule_commands(rule):
    act = rule.get("action")
    if act == "move":
        return ['fileinto %s;' % q(rule.get("folder") or "INBOX")] if (rule.get("folder") or "").strip() else None
    if act in ACTIONS:
        kind, val = ACTIONS[act]
        return ["%s %s;" % (kind, q(val))] + (["stop;"] if kind == "fileinto" else [])
    return None


def generate(rules, absence=None, today_range=None, addresses=()) -> str:
    """Script Sieve complet. absence : dict (enabled, subject, body, start, end ISO) ; addresses : adresses propres (:addresses)."""
    need = {"fileinto", "imap4flags"}
    out = []
    if absence and absence.get("enabled") and absence.get("start") and absence.get("end"):
        need |= {"vacation", "date", "relational"}
        adr = (" :addresses [%s]" % ", ".join(q(a) for a in addresses)) if addresses else ""
        out.append(VACATION
                   % (q(absence["start"]), q(absence["end"]), adr, q(absence.get("subject") or ""), q(absence.get("body") or "")))
    for r in rules or []:
        t, c = rule_test(r), rule_commands(r)
        if t and c:
            out.append("if %s {\n  %s\n}" % (t, "\n  ".join(c)))
    if not out:
        need = set()
    head = ("require [%s];\n" % ", ".join(q(x) for x in sorted(need))) if need else ""
    return "# Generated by MintMail: do not edit by hand (replaced at each upload)\n" + head + "\n".join(out) + "\n"


# ---------------------------------------------------------------- Thunderbird
def parse_thunderbird_filters(text):
    """msgFilterRules.dat → (règles MintMail, nombre de filtres ignorés)."""
    blocks, cur = [], None
    for line in text.splitlines():
        m = re.match(r'^(\w+)="(.*)"\s*$', line.strip())
        if not m:
            continue
        k, v = m.group(1), m.group(2)
        if k == "name":
            cur = {"name": v}
            blocks.append(cur)
        elif cur is not None:
            cur.setdefault(k, v)
    rules, skipped = [], 0
    for b in blocks:
        r = _tb_rule(b)
        if r:
            rules.append(r)
        else:
            skipped += 1
    return rules, skipped


def _tb_rule(b):
    if b.get("enabled", "yes") != "yes":
        return None
    conds = re.findall(r"\(([^,()]+),([^,()]+),([^)]*)\)", b.get("condition", ""))
    if len(conds) != 1 or not b.get("action"):                    # une seule condition « contient » : le reste ne se traduit pas fidèlement
        return None
    field, op, val = (x.strip() for x in conds[0])
    field = {"from": "from", "subject": "subject", "to": "to", "cc": "to", "to or cc": "to"}.get(field.lower())
    if not field or op.lower() != "contains" or not val:
        return None
    act, value = b["action"], urllib.parse.unquote(b.get("actionValue", ""))
    if act == "Move to folder":
        folder = value.rstrip("/").split("/")[-1] if value else ""
        return {"field": field, "text": val, "action": "move", "folder": folder} if folder else None
    simple = {"Mark read": "read", "Mark flagged": "star", "Delete": "trash"}
    return {"field": field, "text": val, "action": simple[act], "folder": ""} if act in simple else None


def merge_rules(existing, new):
    """Ajoute les règles qui n'existent pas déjà ; retourne (liste, nombre ajouté)."""
    seen = {(r.get("field"), (r.get("text") or "").lower(), r.get("action"), r.get("folder", "")) for r in existing}
    out, n = list(existing), 0
    for r in new:
        key = (r["field"], r["text"].lower(), r["action"], r.get("folder", ""))
        if key not in seen:
            out.append(r)
            seen.add(key)
            n += 1
    return out, n


# ---------------------------------------------------------------- ManageSieve
class SieveError(Exception):
    pass


class ManageSieve:
    """Client minimal : STARTTLS (ou TLS direct), AUTHENTICATE PLAIN, PUTSCRIPT, SETACTIVE, DELETESCRIPT."""

    def __init__(self, host, port=4190, timeout=15, sock=None, tls=True):
        self.sock = sock or socket.create_connection((host, port), timeout=timeout)
        self.host, self.tls, self.buf = host, tls, b""
        self._read_status()                                         # bannière : capacités puis OK

    def _readline(self):
        while b"\r\n" not in self.buf:
            d = self.sock.recv(4096)
            if not d:
                raise SieveError("connection closed")
            self.buf += d
        line, self.buf = self.buf.split(b"\r\n", 1)
        return line.decode("utf-8", "replace")

    def _read_status(self):
        lines = []
        while True:
            line = self._readline()
            if line.upper().startswith(("OK", "NO", "BYE")):
                if not line.upper().startswith("OK"):
                    raise SieveError(line)
                return lines
            lines.append(line)

    def _send(self, text):
        self.sock.sendall(text.encode("utf-8") + b"\r\n")

    def starttls(self, context=None):
        self._send("STARTTLS")
        self._read_status()
        self.sock = (context or ssl.create_default_context()).wrap_socket(self.sock, server_hostname=self.host)
        self.buf = b""
        self._read_status()                                         # RFC 5804 : après TLS le serveur redonne ses capacités (puis OK)

    def login(self, user, password):
        tok = base64.b64encode(("\0%s\0%s" % (user, password)).encode("utf-8")).decode()
        self._send('AUTHENTICATE "PLAIN" "%s"' % tok)
        self._read_status()

    def put(self, name, script):
        raw = script.encode("utf-8")
        self.sock.sendall(('PUTSCRIPT %s {%d+}\r\n' % (q(name), len(raw))).encode("utf-8") + raw + b"\r\n")
        self._read_status()

    def activate(self, name):
        self._send("SETACTIVE %s" % q(name))
        self._read_status()

    def deactivate(self):
        self._send('SETACTIVE ""')
        self._read_status()

    def close(self):
        try:
            self._send("LOGOUT")
        except OSError:
            pass
        try:
            self.sock.close()
        except OSError:
            pass


def publish(host, user, password, script, port=4190, connect=ManageSieve, name=SCRIPT_NAME, tls=True):
    """Envoie et active le script ; SieveError en cas de refus (serveur sans ManageSieve, identifiants, script invalide)."""
    try:
        c = connect(host, port)
    except OSError as e:
        raise SieveError(str(e))
    try:
        if tls:
            c.starttls()
        c.login(user, password)
        c.put(name, script)
        c.activate(name)
    except OSError as e:
        raise SieveError(str(e))
    finally:
        c.close()


# ---------------------------------------------------------------- comptes
NO_SIEVE = ("gmail.com", "googlemail.com", "outlook.com", "office365.com", "hotmail.com", "live.com", "yahoo.com", "icloud.com", "me.com")


def supports(account) -> bool:
    """Boîte susceptible d'offrir Sieve : mot de passe (pas OAuth) et serveur qui n'est pas un grand service sans Sieve."""
    host = str(account.get("imap_host") or "").lower()
    if account.get("demo") or not host or account.get("auth") == "oauth2" or account.get("oauth"):
        return False
    return not any(host == d or host.endswith("." + d) for d in NO_SIEVE)


def publish_accounts(accounts, password_of, rules, absence=None, own_of=lambda a: (), port=4190, tls=True, connect=ManageSieve):
    """Envoie le script à chaque boîte concernée ; retourne [(email, "ok" | "unsupported" | message d'erreur)]. L'absence n'est envoyée qu'aux boîtes ciblées."""
    out = []
    for a in accounts:
        if not supports(a):
            out.append((a.get("email", ""), "unsupported"))
            continue
        targeted = absence and (not absence.get("accounts") or a.get("id") in absence["accounts"])
        script = generate(rules, absence if targeted else None, addresses=sorted(own_of(a)))
        try:
            publish(a["imap_host"], a.get("username") or a["email"], password_of(a["id"]), script, port=port, tls=tls, connect=connect)
            out.append((a["email"], "ok"))
        except SieveError as e:
            out.append((a["email"], str(e) or "error"))
    return out
